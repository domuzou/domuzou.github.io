/* ---------- 描画ヘルパー ---------- */
const NF_CACHE = {};
function NF_canvas(name) {
  if (NF_CACHE[name]) return NF_CACHE[name];
  const sp = NF_SPRITES[name];
  if (!sp) return null;
  const h = sp.rows.length, w = sp.rows[0].length;
  const cv = document.createElement("canvas");
  cv.width = w; cv.height = h;
  const ctx = cv.getContext("2d");
  for (let y = 0; y < h; y++) {
    const row = sp.rows[y];
    for (let x = 0; x < row.length; x++) {
      const col = sp.pal[row[x]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x, y, 1, 1);
    }
  }
  NF_CACHE[name] = cv;
  return cv;
}
function NF_draw(ctx, name, x, y, scale) {
  const cv = NF_canvas(name);
  if (!cv) return;
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(cv, x, y, cv.width * scale, cv.height * scale);
}
function NF_img(name, scale) {
  const cv = NF_canvas(name);
  if (!cv) return "";
  return cv.toDataURL();
}
